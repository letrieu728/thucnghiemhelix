import json
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

# Base paths
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
CLOSED_LOOP_ROOT = PROJECT_ROOT / "closed-loop"
RAW_TRACES_DIR = CLOSED_LOOP_ROOT / "data" / "raw_traces"
PROCESSED_DIR = CLOSED_LOOP_ROOT / "data" / "processed"

SYSTEM_PROMPT = (
    "You are an expert autonomous software engineer. "
    "Write concise, optimal, robust, and well-tested code that precisely fulfills the user requirements."
)


# ------------------------------------------------------------------------------
# 1. Trajectory Reader & Grouping (live-only by default)
# ------------------------------------------------------------------------------
def is_dry_run_trace(trace: Dict[str, Any]) -> bool:
    """Classify a trace as dry-run (mock) vs live.

    New traces carry an explicit "mode" field written by 02_run_helix_eval.py.
    Legacy traces (committed 2026-10-28/29) have no mode field: live ones
    always carry at least one transcript step, while all 31 dry-run traces
    have an empty raw_helix_transcript. A live trace whose first API call
    failed before any reply also has an empty transcript and is conservatively
    skipped -- it carries no usable solution anyway.
    """
    mode = trace.get("mode")
    if mode == "dry-run":
        return True
    if mode == "live":
        return False
    return not trace.get("raw_helix_transcript")


def load_all_traces(
    traces_dir: Path, allow_dry_run: bool = False
) -> Dict[str, List[Dict[str, Any]]]:
    """Loads BUILD-phase traces from directory and groups them by task_id.

    Dry-run traces are skipped unless allow_dry_run is True. Skipped files
    are reported, never silently dropped. Each kept trace gains a
    "_source_file" key (the trace filename) so extracted records stay
    traceable to their source run.
    """
    grouped_traces = defaultdict(list)
    skipped: List[str] = []
    if not traces_dir.exists():
        return grouped_traces

    for file_path in traces_dir.glob("*.json"):
        try:
            with open(file_path, "r", encoding="utf-8") as f:
                trace = json.load(f)

            if trace.get("phase") != "build":
                continue
            if not allow_dry_run and is_dry_run_trace(trace):
                skipped.append(file_path.name)
                continue
            task_id = trace.get("task_id")
            if task_id:
                trace["_source_file"] = file_path.name
                grouped_traces[task_id].append(trace)
        except Exception as e:
            print(f"[WARN] Failed to read {file_path.name}: {e}")

    kept = sum(len(v) for v in grouped_traces.values())
    print(f"[PROVENANCE] Kept {kept} live BUILD traces across {len(grouped_traces)} tasks.")
    if skipped:
        print(
            f"[PROVENANCE] Skipped {len(skipped)} dry-run BUILD traces "
            f"(use --allow-dry-run to include them for smoke tests only):"
        )
        for name in sorted(skipped):
            print(f"  - {name}")
    return grouped_traces


# ------------------------------------------------------------------------------
# 2. SFT & DPO Extraction Logic
# ------------------------------------------------------------------------------
def extract_sft_records(grouped_traces: Dict[str, List[Dict[str, Any]]]) -> List[Dict[str, Any]]:
    """
    Extracts high-quality SFT training records:
    For each task, pick the passed solution with minimal steps and cleanest solution.
    """
    sft_records = []

    for task_id, traces in grouped_traces.items():
        # Filter only passed traces
        passed_traces = [t for t in traces if t.get("passed") is True and t.get("assistant_solution")]
        if not passed_traces:
            continue

        # Sort by step count (prefer most efficient solution), then latency
        best_trace = min(passed_traces, key=lambda t: (t.get("steps", 999), t.get("latency_sec", 999)))

        user_content = best_trace.get("prompt", "")
        assistant_content = best_trace.get("assistant_solution", "")

        # Standard OpenAI / ChatML messages format
        record = {
            "task_id": task_id,
            "harness_source": best_trace.get("harness_id"),
            "steps": best_trace.get("steps"),
            "source_trace": best_trace.get("_source_file"),
            "messages": [
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": user_content},
                {"role": "assistant", "content": assistant_content},
            ],
        }
        sft_records.append(record)

    return sft_records


def extract_dpo_pairs(grouped_traces: Dict[str, List[Dict[str, Any]]]) -> List[Dict[str, Any]]:
    """
    Constructs (chosen, rejected) preference pairs from sibling trajectories on identical tasks:
    1. Primary preference: Passed (chosen) vs Failed (rejected)
    2. Secondary preference: Passed with fewer steps/cleaner code vs Passed with bloat/retries
    """
    dpo_pairs = []

    for task_id, traces in grouped_traces.items():
        if len(traces) < 2:
            continue

        passed_traces = [t for t in traces if t.get("passed") is True and t.get("assistant_solution")]
        failed_traces = [t for t in traces if t.get("passed") is False and t.get("assistant_solution")]

        # Case 1: Clear winner (Passed vs Failed)
        if passed_traces and failed_traces:
            best_chosen = min(passed_traces, key=lambda t: t.get("steps", 999))
            worst_rejected = max(failed_traces, key=lambda t: t.get("steps", 0))

            dpo_pairs.append({
                "task_id": task_id,
                "preference_type": "correctness_contrast",
                "system": SYSTEM_PROMPT,
                "prompt": best_chosen.get("prompt"),
                "chosen": best_chosen.get("assistant_solution"),
                "rejected": worst_rejected.get("assistant_solution"),
                "chosen_harness": best_chosen.get("harness_id"),
                "rejected_harness": worst_rejected.get("harness_id"),
                "chosen_steps": best_chosen.get("steps"),
                "rejected_steps": worst_rejected.get("steps"),
                "chosen_source_trace": best_chosen.get("_source_file"),
                "rejected_source_trace": worst_rejected.get("_source_file"),
            })

        # Case 2: Efficiency contrast (Both passed, but one took >= 2x more steps or had retries)
        elif len(passed_traces) >= 2:
            sorted_by_steps = sorted(passed_traces, key=lambda t: t.get("steps", 999))
            fastest = sorted_by_steps[0]
            slowest = sorted_by_steps[-1]

            if (slowest.get("steps", 1) - fastest.get("steps", 1)) >= 2:
                dpo_pairs.append({
                    "task_id": task_id,
                    "preference_type": "efficiency_contrast",
                    "system": SYSTEM_PROMPT,
                    "prompt": fastest.get("prompt"),
                    "chosen": fastest.get("assistant_solution"),
                    "rejected": slowest.get("assistant_solution"),
                    "chosen_harness": fastest.get("harness_id"),
                    "rejected_harness": slowest.get("harness_id"),
                    "chosen_steps": fastest.get("steps"),
                    "rejected_steps": slowest.get("steps"),
                    "chosen_source_trace": fastest.get("_source_file"),
                    "rejected_source_trace": slowest.get("_source_file"),
                })

    return dpo_pairs


