def sha256_file(path: Path) -> str:
    """SHA-256 hex digest of a file (for the provenance manifest)."""
    digest = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()


def count_dry_run_build_traces(traces_dir: Path) -> int:
    """Count BUILD-phase traces classified as dry-run, without loading groups."""
    count = 0
    if not traces_dir.exists():
        return count
    for file_path in traces_dir.glob("*.json"):
        try:
            with open(file_path, "r", encoding="utf-8") as f:
                trace = json.load(f)
        except Exception:
            continue
        if trace.get("phase") == "build" and is_dry_run_trace(trace):
            count += 1
    return count


def write_provenance_manifest(
    grouped: Dict[str, List[Dict[str, Any]]],
    allow_dry_run: bool,
    sft_out_path: Path,
    dpo_out_path: Path,
    sft_count: int,
    dpo_count: int,
) -> Path:
    """Write provenance.json next to the datasets for 04_train_lora.py."""
    dry_run_present = count_dry_run_build_traces(RAW_TRACES_DIR)
    kept = sum(len(v) for v in grouped.values())
    manifest = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "extractor": "03_extract_pairs.py (live-only guard, 2026-11-12)",
        "allow_dry_run": allow_dry_run,
        "live_traces_kept": kept,
        "dry_run_build_traces_present": dry_run_present,
        "dry_run_traces_skipped": 0 if allow_dry_run else dry_run_present,
        "tasks": sorted(grouped),
        "counts": {"sft": sft_count, "dpo": dpo_count},
        "data_sha256": {
            "sft_data.jsonl": sha256_file(sft_out_path),
            "dpo_pairs.jsonl": sha256_file(dpo_out_path),
        },
        "source_traces": sorted(
            {t.get("_source_file") for traces in grouped.values() for t in traces if t.get("_source_file")}
        ),
    }
    out_path = PROCESSED_DIR / "provenance.json"
    out_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8")
    return out_path


# ------------------------------------------------------------------------------
# 4. Main Execution
# ------------------------------------------------------------------------------
def main():
    parser = argparse.ArgumentParser(description="Extract SFT & DPO training data from HELIX sibling traces")
    parser.add_argument("--seed-demo", action="store_true", help="Generate synthetic sibling traces for instant demo")
    parser.add_argument(
        "--allow-dry-run",
        action="store_true",
        help="Include dry-run (mock) traces. SMOKE TESTS ONLY -- never train on the output.",
    )
    args = parser.parse_args()

    PROCESSED_DIR.mkdir(parents=True, exist_ok=True)

    # Seeded demo traces are synthetic by construction: including them
    # requires the dry-run path, labelled as demo-only.
    allow_dry_run = args.allow_dry_run or args.seed_demo
    if args.seed_demo:
        print("[WARN] --seed-demo generates SYNTHETIC traces; output is demo-only, do not train on it.")

    grouped = load_all_traces(RAW_TRACES_DIR, allow_dry_run=allow_dry_run)
    if args.seed_demo:
        seed_demo_traces()
        grouped = load_all_traces(RAW_TRACES_DIR, allow_dry_run=allow_dry_run)

    if not grouped:
        raise SystemExit(
            "No live BUILD traces found; provide live input traces, or explicitly use "
            "--seed-demo / --allow-dry-run for a smoke test (demo output only)."
        )

    print(f"\nLoaded {sum(len(v) for v in grouped.values())} traces across {len(grouped)} tasks from {RAW_TRACES_DIR}")

    # 1. Extract Clean SFT Dataset
    sft_records = extract_sft_records(grouped)
    sft_out_path = PROCESSED_DIR / "sft_data.jsonl"
    with open(sft_out_path, "w", encoding="utf-8") as f:
        for rec in sft_records:
            f.write(json.dumps(rec, ensure_ascii=False) + "\n")
    print(f"[OK] Extracted {len(sft_records)} Clean SFT records -> {sft_out_path}")

    # 2. Extract DPO Preference Pairs
    dpo_pairs = extract_dpo_pairs(grouped)
    dpo_out_path = PROCESSED_DIR / "dpo_pairs.jsonl"
    with open(dpo_out_path, "w", encoding="utf-8") as f:
        for pair in dpo_pairs:
            f.write(json.dumps(pair, ensure_ascii=False) + "\n")
    print(f"[OK] Extracted {len(dpo_pairs)} DPO Preference Pairs -> {dpo_out_path}\n")

    # 3. Provenance manifest (04_train_lora.py verifies it before training)
    manifest_path = write_provenance_manifest(
        grouped, allow_dry_run, sft_out_path, dpo_out_path, len(sft_records), len(dpo_pairs)
    )
    print(f"[OK] Wrote provenance manifest -> {manifest_path}")


if __name__ == "__main__":
    main()
