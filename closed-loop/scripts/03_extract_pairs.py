"""
03_extract_pairs.py - Sibling Trajectory Extraction & Alignment Filtering
==========================================================================
Implements the core data synthesis mechanism of HELIX Closed-Loop:
Sibling Trajectory Contrastive Distillation.

Algorithm:
1. Groups raw agent trajectories from `closed-loop/data/raw_traces/` by `task_id`.
2. Cross-examines outcomes across the 4 harnesses on the identical problem:
   - SFT Extraction (Supervised Fine-Tuning):
     Selects verified correct (`passed == True`), concise, tool-disciplined
     trajectories (e.g., from OpenCode / Hermes Agent) and normalizes them into
     standard ChatML instruction-tuning records.
   - DPO Preference Extraction (Direct Preference Optimization):
     Pairs a clean successful trajectory (`chosen`) with a degraded or failed
     trajectory (`rejected`) generated by a less capable harness (e.g., Minimal failing
     or looping without structured context).

Outputs:
  - `closed-loop/data/processed/sft_data.jsonl`
  - `closed-loop/data/processed/dpo_pairs.jsonl`
  - `closed-loop/data/processed/provenance.json` (counts, source traces and
    SHA-256 hashes of the two datasets; 04_train_lora.py refuses to train
    when this manifest is missing, allows dry-run data, or no longer matches
    the dataset files)

Provenance guard (added 2026-11-12, see closed-loop/PROVENANCE_AUDIT.md):
  By default ONLY live traces are extracted. A trace counts as live when
  "mode" == "live", or -- for traces written before the mode field existed --
  when it carries a non-empty raw_helix_transcript. Dry-run traces (mock
  solutions from 02_run_helix_eval.py --mode dry-run) are skipped and
  counted, because the committed BUILD set mixed 31 dry-run traces in with
  9 live ones and the old extractor silently distilled hand-written mock
  code. Pass --allow-dry-run ONLY for offline pipeline smoke tests, and
  never train on its output. Seeded demo traces (--seed-demo) are treated
  as dry-run by the same rule.

Usage:
  python closed-loop/scripts/03_extract_pairs.py
  python closed-loop/scripts/03_extract_pairs.py --allow-dry-run  # smoke test only, do NOT train on output
  python closed-loop/scripts/03_extract_pairs.py --seed-demo  # generate baseline mock traces if raw_traces is empty (demo only)
"""

import argparse
